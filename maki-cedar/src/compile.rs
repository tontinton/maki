use crate::{CTX_SCOPE, CedarError, TOOL_TYPE};

/// How a scopeless default behaves when no rule matches. Mirrors maki's
/// `DefaultEffect` without depending on `maki-config`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DefaultModel {
    Allow,
    Deny,
    Prompt,
}

/// One maki permission rule, flattened to the fields Cedar needs.
#[derive(Debug, Clone)]
pub struct RuleModel {
    /// The `ToolKey` display string: `bash`, `server.tool`, `server` (a whole
    /// MCP server), or `*` (all tools).
    pub tool_key: String,
    /// `true` if `tool_key` names a whole MCP server, which compiles to a
    /// prefix match on the resource id instead of an exact match.
    pub server_wildcard: bool,
    /// The scope pattern (`git *`, `src/**`, `*`), or `None` for all scopes.
    pub scope: Option<String>,
    /// `true` = permit, `false` = forbid.
    pub allow: bool,
}

/// maki's merged permission configuration, independent of `maki-config`. The
/// caller (maki-agent) translates `PermissionsConfig` into this.
#[derive(Debug, Clone)]
pub struct PermissionsModel {
    pub default: DefaultModel,
    pub rules: Vec<RuleModel>,
}

/// A Cedar scope pattern treated as universal: no `when` clause is emitted, so
/// the rule covers every scope of its tool.
fn is_universal(scope: &str) -> bool {
    matches!(scope, "*" | "**" | "/**")
}

/// Cedar string-literal escaping. maki scope patterns use `*` as the Cedar
/// `like` wildcard on purpose, so it passes through; only `"` and `\` escape.
fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn policy_for(rule: &RuleModel) -> String {
    let effect = if rule.allow { "permit" } else { "forbid" };

    let resource = if rule.tool_key == "*" {
        String::new()
    } else if rule.server_wildcard {
        format!(", resource is {TOOL_TYPE}")
    } else {
        format!(", resource == {TOOL_TYPE}::\"{}\"", escape(&rule.tool_key))
    };

    let mut conditions: Vec<String> = Vec::new();
    if rule.server_wildcard {
        conditions.push(format!(
            "resource.name like \"{}.*\"",
            escape(&rule.tool_key)
        ));
    }
    if let Some(s) = &rule.scope
        && !is_universal(s)
    {
        conditions.push(format!("context.{CTX_SCOPE} like \"{}\"", escape(s)));
    }

    let when = if conditions.is_empty() {
        String::new()
    } else {
        format!(" when {{ {} }}", conditions.join(" && "))
    };

    format!("{effect}(principal, action{resource}){when};")
}

/// Compile a maki permissions model into `(policies, schema)` Cedar source
/// text. The schema is the human `.cedarschema` form.
///
/// The default effect is NOT encoded as a Cedar policy: Cedar stays silent
/// (`NoDecision`) when no rule matches, and maki applies its own default, so a
/// round trip through Cedar never changes the fall-through behaviour.
pub fn compile(model: &PermissionsModel) -> Result<(String, String), CedarError> {
    let mut out = format!(
        "// Generated by `maki permissions export-cedar` from permissions.toml.\n\
         // Default effect (no rule matched) stays with maki: {:?}.\n\n",
        model.default
    );
    for rule in &model.rules {
        out.push_str(&policy_for(rule));
        out.push('\n');
    }
    // Validate what we generated so a bad rule fails at export, not at load.
    crate::CedarEngine::from_source(&out, Some(schema()))?;
    Ok((out, schema().to_string()))
}

/// The reference Cedar schema for maki's permission model. Embedded as a
/// string so packaging never has to carry a separate asset. The same text is
/// mirrored at `maki-cedar/schema/maki.cedarschema` for readers who want the
/// file; a test keeps the two in sync.
pub fn schema() -> &'static str {
    SCHEMA
}

const SCHEMA: &str = r#"// Cedar schema for maki's permission model.
//
// maki has one principal, the agent itself, and one action, invoking a tool.
// The resource is the tool being invoked, named by its tool key (bash,
// server.tool). The requested scope (a path, a bash command, any free-form
// string) and the tool key travel in the action context, so policies read
// context.scope and context.tool and one schema covers every tool.

entity Agent;

entity Tool = {
    "name": String,
};

action invoke
    appliesTo {
        principal: [Agent],
        resource: [Tool],
        context: {
            "scope": String,
            "tool": String,
        },
    };
"#;

#[cfg(test)]
mod tests {
    use super::{DefaultModel, PermissionsModel, RuleModel, compile, policy_for};
    use crate::{CedarDecision, CedarEngine};

    fn rule(tool: &str, scope: Option<&str>, allow: bool) -> RuleModel {
        RuleModel {
            tool_key: tool.to_string(),
            server_wildcard: false,
            scope: scope.map(str::to_string),
            allow,
        }
    }

    #[test]
    fn permit_scope_compiles_to_like() {
        let p = policy_for(&rule("bash", Some("git *"), true));
        assert!(p.contains(r#"resource == Tool::"bash""#), "got {p}");
        assert!(p.contains(r#"context.scope like "git *""#), "got {p}");
        assert!(p.starts_with("permit("), "got {p}");
    }

    #[test]
    fn universal_scope_omits_when() {
        assert!(!policy_for(&rule("bash", Some("*"), true)).contains("when"));
    }

    #[test]
    fn wildcard_tool_omits_resource() {
        assert!(policy_for(&rule("*", None, false)).starts_with("forbid(principal, action)"));
    }

    #[test]
    fn embedded_schema_matches_reference_file() {
        // The const is the build's source of truth; the file is for readers.
        // Keep them identical so docs never drift from what the engine uses.
        let file = include_str!("../schema/maki.cedarschema");
        assert_eq!(super::schema(), file);
    }

    #[test]
    fn compile_round_trips_through_engine() {
        let model = PermissionsModel {
            default: DefaultModel::Prompt,
            rules: vec![
                rule("bash", Some("git *"), true),
                rule("bash", Some("rm *"), false),
                rule("edit", Some("src/**"), true),
            ],
        };
        let (policies, schema) = compile(&model).expect("compile");
        let engine = CedarEngine::from_source(&policies, Some(&schema)).expect("recompile");

        assert_eq!(
            engine.decide("bash", Some("git status")),
            CedarDecision::Allow
        );
        match engine.decide("bash", Some("rm -rf /")) {
            CedarDecision::Deny(_) => {}
            other => panic!("expected Deny, got {other:?}"),
        }
        assert_eq!(
            engine.decide("edit", Some("src/a.rs")),
            CedarDecision::Allow
        );
        assert_eq!(
            engine.decide("bash", Some("npm install")),
            CedarDecision::NoDecision
        );
    }
}
